'use strict';

const common = require('../common');
const assert = require('assert');
const { spawnSync } = require('child_process');
const vm = require('vm');

const childMode = process.env.REX_DIAGNOSTICS_CHILD;

if (childMode === 'codegen-worker') {
  runCodeGenerationWorkerChild();
} else if (childMode) {
  runExceptionChild(childMode);
} else {
  runCodeGenerationTests();
  runExceptionTests();
}

function runCodeGenerationTests() {
  const realmTime = process._realmTime;
  assert.strictEqual(typeof realmTime.setCodeGenerationCallback, 'function');
  assert.strictEqual(typeof realmTime.getCodeGenerationRecords, 'function');

  const context = vm.createContext({ marker: 41 });
  const seen = [];
  let callbackDepth = 0;
  const dispose = realmTime.setCodeGenerationCallback((info, control) => {
    callbackDepth++;
    assert.strictEqual(callbackDepth, 1);
    seen.push(info);

    // Code generated by the trusted callback itself must not recurse.
    Function('return 1')();
    if (info.source.includes('__REX_DYNAMIC__')) {
      control.replaceSource(
        info.source.replaceAll('__REX_DYNAMIC__', 'marker'));
    }
    callbackDepth--;
  }, { rootSource: 'realm-diagnostics-test' });

  assert.strictEqual(vm.runInContext(`
    (function directEvalLexicalScope() {
      const marker = 41;
      return eval('__REX_DYNAMIC__ + 1');
    })()
  `, context), 42);
  assert.strictEqual(vm.runInContext(
    `(0, eval)('__REX_DYNAMIC__ + 1')`, context), 42);
  assert.strictEqual(vm.runInContext(`
    (function strictDirectEvalLexicalScope() {
      'use strict';
      const marker = 41;
      return eval('__REX_DYNAMIC__ + 1');
    })()
  `, context), 42);
  assert.strictEqual(vm.runInContext(
    `eval('__REX_DYNAMIC__ + 1\\n//# sourceURL=dynamic-eval.js')`,
    context,
  ), 42);
  assert.strictEqual(vm.runInContext(
    `Function('return __REX_DYNAMIC__ + 1')()`, context), 42);
  assert.strictEqual(vm.runInContext(
    `(function noop() {}).constructor('return __REX_DYNAMIC__ + 1')()`,
    context), 42);
  assert.strictEqual(new vm.Script(
    '__REX_DYNAMIC__ + 1',
    { filename: 'realm-diagnostics.vm.js' },
  ).runInContext(context), 42);
  assert.strictEqual(vm.compileFunction(
    'return __REX_DYNAMIC__ + value',
    ['value'],
    { parsingContext: context, filename: 'realm-compile-function.vm.js' },
  )(1), 42);
  assert.strictEqual(vm.runInNewContext(
    '__REX_DYNAMIC__ + 1',
    { marker: 41 },
    { filename: 'realm-run-in-new-context.vm.js' },
  ), 42);
  assert.strictEqual(vm.runInContext(
    `eval("Function('return __REX_DYNAMIC__ + 1')()")`, context), 42);
  vm.runInContext(`
    Object.getPrototypeOf(async function() {}).constructor(
      'return __REX_DYNAMIC__ + 1');
    Object.getPrototypeOf(function*() {}).constructor(
      'return __REX_DYNAMIC__ + 1');
    Object.getPrototypeOf(async function*() {}).constructor(
      'return __REX_DYNAMIC__ + 1');
  `, context);

  const kinds = new Set(seen.map((entry) => entry.kind));
  assert(kinds.has('eval'));
  assert(kinds.has('Function'));
  assert(kinds.has('AsyncFunction'));
  assert(kinds.has('GeneratorFunction'));
  assert(kinds.has('AsyncGeneratorFunction'));
  assert(kinds.has('vm.Script'));
  assert(kinds.has('vm.compileFunction'));
  assert(seen.some((entry) => entry.sourceURL === 'dynamic-eval.js'));
  for (const info of seen) {
    assert.strictEqual(info.rootSourceId, 'realm-diagnostics-test');
    assert.match(info.sourceHash, /^[a-f0-9]{64}$/);
    assert.strictEqual(typeof info.codegenId, 'number');
  }

  const records = realmTime.getCodeGenerationRecords();
  assert(records.length >= 5);
  assert(records.every((record) => record.callbackError === false));
  assert(records.some((record) => record.replaced === true));
  const recordCountBeforeSyntaxError = records.length;
  assert.throws(
    () => vm.runInContext(`eval('function (')`, context),
    /Function statements require a function name|Unexpected token/,
  );
  const syntaxRecords = realmTime.getCodeGenerationRecords()
    .slice(recordCountBeforeSyntaxError);
  assert(syntaxRecords.some((record) => record.kind === 'eval'));

  assert.strictEqual(dispose(), true);
  assert.strictEqual(dispose(), false);
  const beforeDisposedEval = seen.length;
  assert.strictEqual(vm.runInContext('20 + 22', context), 42);
  assert.strictEqual(seen.length, beforeDisposedEval);

  const callbackFailureDispose = realmTime.setCodeGenerationCallback(() => {
    throw new Error('trusted callback failed');
  });
  assert.strictEqual(vm.runInContext(`eval('20 + 22')`, context), 42);
  assert.strictEqual(
    realmTime.getCodeGenerationRecords().at(-1).callbackError,
    true,
  );
  assert.strictEqual(callbackFailureDispose(), true);

  const vmKinds = [];
  const noVmDispose = realmTime.setCodeGenerationCallback((info) => {
    vmKinds.push(info.kind);
  }, { includeVmCompile: false });
  assert.strictEqual(new vm.Script('20 + 22').runInThisContext(), 42);
  assert.strictEqual(eval('20 + 22'), 42);
  assert(!vmKinds.includes('vm.Script'));
  assert(vmKinds.includes('eval'));
  assert.strictEqual(noVmDispose(), true);

  const boundedDispose = realmTime.setCodeGenerationCallback(() => {});
  for (let index = 0; index < 520; index++) eval(String(index));
  const boundedRecords = realmTime.getCodeGenerationRecords();
  assert.strictEqual(boundedRecords.length, 512);
  assert(boundedRecords[0].codegenId < boundedRecords.at(-1).codegenId);
  assert.strictEqual(boundedDispose(), true);

  const worker = spawnSync(process.execPath, [__filename], {
    encoding: 'utf8',
    env: { ...process.env, REX_DIAGNOSTICS_CHILD: 'codegen-worker' },
  });
  assert.strictEqual(worker.status, 0, worker.stderr);
  assert.match(worker.stdout, /realm-diagnostics:codegen-worker:ok/);
}

function runCodeGenerationWorkerChild() {
  const { Worker } = require('worker_threads');
  const source = `
    const assert = require('assert');
    const { parentPort } = require('worker_threads');
    const seen = [];
    const dispose = process._realmTime.setCodeGenerationCallback((info) => {
      seen.push(info.kind);
    });
    assert.strictEqual(eval('20 + 22'), 42);
    assert.strictEqual(Function('return 42')(), 42);
    assert.strictEqual(dispose(), true);
    parentPort.postMessage(seen);
  `;
  const worker = new Worker(source, { eval: true });
  worker.once('message', common.mustCall((seen) => {
    assert(seen.includes('eval'));
    assert(seen.includes('Function'));
    process.stdout.write('realm-diagnostics:codegen-worker:ok\n');
  }));
}

function runExceptionTests() {
  for (const mode of [
    'replace',
    'replace-undefined',
    'preserve',
    'callback-error',
    'unhandled-rejection',
    'ignore-unhandled-rejection',
  ]) {
    const child = spawnSync(process.execPath, [__filename], {
      encoding: 'utf8',
      env: { ...process.env, REX_DIAGNOSTICS_CHILD: mode },
    });
    assert.strictEqual(child.status, 0, child.stderr);
    assert.match(child.stdout, new RegExp(`realm-diagnostics:${mode}:ok`));
  }

  const stock = spawnSync(
    process.execPath,
    ['-e', 'setImmediate(() => { throw new Error("stock-path"); })'],
    { encoding: 'utf8' },
  );
  assert.strictEqual(stock.status, 1);
  assert.match(stock.stderr, /stock-path/);
}

function runExceptionChild(mode) {
  const realmTime = process._realmTime;
  assert.strictEqual(typeof realmTime.setUncaughtExceptionCallback, 'function');
  assert.strictEqual(typeof realmTime.getExceptionRecords, 'function');
  const realmContext = vm.createContext({});
  realmTime.enable(realmContext);

  let callbackCalls = 0;
  let dispose;
  if (mode === 'callback-error') {
    dispose = realmTime.setUncaughtExceptionCallback(() => {
      callbackCalls++;
      throw new Error('callback-failure');
    });
  } else {
    dispose = realmTime.setUncaughtExceptionCallback((exception, info, control) => {
      callbackCalls++;
      assert.strictEqual(typeof info.exceptionId, 'number');
      assert(info.realmGeneration > 0);
      assert.strictEqual(info.rootSourceId, 'exception-test-root');
      assert.strictEqual(typeof info.realmTimeNs, 'bigint');
      assert.strictEqual(typeof info.hostMonotonicNs, 'bigint');
      assert(Array.isArray(info.frames));
      assert(info.frames.length > 0);
      if (mode === 'replace') {
        assert.strictEqual(info.origin, 'uncaughtException');
        assert.strictEqual(exception.message, 'original-exception');
        control.replace(new Error('replacement-exception'));
      } else if (mode === 'replace-undefined') {
        control.replace(undefined);
      } else if (mode === 'preserve') {
        assert.strictEqual(info.origin, 'uncaughtException');
        assert.strictEqual(exception.message, 'original-exception');
      } else {
        assert.strictEqual(info.origin, 'unhandledRejection');
      }
    }, {
      context: realmContext,
      rootSource: 'exception-test-root',
      includeConfirmedUnhandledRejection:
        mode !== 'ignore-unhandled-rejection',
    });
  }

  process.once('uncaughtException', common.mustCall((error, origin) => {
    const records = realmTime.getExceptionRecords();
    if (mode === 'replace') {
      assert.strictEqual(error.message, 'replacement-exception');
      assert.strictEqual(records.at(-1).replaced, true);
      assert.strictEqual(callbackCalls, 1);
    } else if (mode === 'replace-undefined') {
      assert.strictEqual(error, undefined);
      assert.strictEqual(records.at(-1).replaced, true);
      assert.strictEqual(callbackCalls, 1);
    } else if (mode === 'preserve') {
      assert.strictEqual(error.message, 'original-exception');
      assert.strictEqual(records.at(-1).replaced, false);
      assert.strictEqual(callbackCalls, 1);
    } else if (mode === 'callback-error') {
      assert.strictEqual(error.message, 'original-exception');
      assert.strictEqual(records.at(-1).callbackError, true);
      assert.strictEqual(callbackCalls, 1);
    } else if (mode === 'unhandled-rejection') {
      assert.strictEqual(origin, 'unhandledRejection');
      assert.strictEqual(callbackCalls, 1);
    } else {
      assert.strictEqual(origin, 'unhandledRejection');
      assert.strictEqual(callbackCalls, 0);
      assert.strictEqual(records.length, 0);
    }
    assert.strictEqual(dispose(), true);
    realmTime.disable(realmContext);
    process.stdout.write(`realm-diagnostics:${mode}:ok\n`);
  }));

  if (mode === 'unhandled-rejection' ||
      mode === 'ignore-unhandled-rejection') {
    Promise.reject(new Error('original-rejection'));
  } else {
    setImmediate(() => { throw new Error('original-exception'); });
  }
}
